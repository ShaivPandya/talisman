def _string(description: str, **kwargs: Any) -> dict[str, Any]:
    return {"type": "string", "description": description, "maxLength": 160, **kwargs}


def _source(
    source_id: str,
    name: str,
    group: str,
    question: str,
    coverage: str,
    cadence: str,
    url: str,
    adapter: str,
    hosts: list[str],
    *,
    fields: dict[str, Any] | None = None,
    required: list[str] | None = None,
    keys: list[str] | None = None,
    license_url: str | None = None,
    access: str = "public",
    permission: str | None = None,
    freshness_days: int = 10,
    citation: str | None = None,
    notes: str = "",
    authority_rank: int = 1,
) -> dict[str, Any]:
    properties = {
        "start_date": _string("Start date (YYYY-MM-DD); default 90 days ago", format="date"),
        "end_date": _string("End date (YYYY-MM-DD); default today", format="date"),
        "limit": {"type": "integer", "minimum": 1, "maximum": 1000, "default": 500, "description": "Maximum records"},
        **(fields or {}),
    }
    return {
        "source_id": f"alternative_{source_id}",
        "name": name,
        "group": group,
        "question": question,
        "coverage": coverage,
        "cadence": cadence,
        "url": url,
        "adapter": adapter,
        "adapter_version": "1",
        "allowed_hosts": hosts,
        "parameter_schema": {
            "type": "object",
            "properties": properties,
            "required": required or [],
            "additionalProperties": False,
        },
        "required_credentials": keys or [],
        "access": access,
        "permission_env": permission,
        "license_url": license_url or url,
        "access_checked_at": "2026-10-14",
        "attribution": citation or name,
        "storage_allowed": access not in {"reference_only", "license_required"},
        "freshness_days": freshness_days,
        "cache_ttl_seconds": 21600 if freshness_days <= 10 else 86400,
        "notes": notes,
        "authority_rank": authority_rank,
    }


